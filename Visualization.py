import pandas as pd
import matplotlib.pyplot as plt
df = pd.read_csv("cleaned_purchase_data.csv")
basket = pd.read_csv("basket_for_apriori.csv", index_col=0)
df['Date'] = pd.to_datetime(df['Date'])
top_products = df['Product'].value_counts().head(15)
plt.figure(figsize=(10,6))
top_products.plot(kind='bar', color='skyblue')
plt.title("Graph 1: Top 15 Most Frequently Purchased Products")
plt.xlabel("Product")
plt.ylabel("Occurrence Count")
plt.xticks(rotation=45)
plt.tight_layout()
plt.savefig("graph1_top_products.png")
print("Graph1 saved!")
plt.figure(figsize=(10,6))
plt.hist(df['Quantity'], bins=20, color='orange', edgecolor='black')
plt.title("Graph 2: Quantity Distribution")
plt.xlabel("Quantity")
plt.ylabel("Frequency")
plt.tight_layout()
plt.savefig("graph2_quantity.png")
print("Graph2 saved!")
avg_price = df.groupby('Product')['UnitPrice'].mean().sort_values(ascending=False).head(15)
plt.figure(figsize=(10,6))
avg_price.plot(kind='bar', color='green')
plt.title("Graph 3: Average Price - Top 15 Expensive Products")
plt.xlabel("Product")
plt.ylabel("Avg Unit Price")
plt.xticks(rotation=45)
plt.tight_layout()
plt.savefig("graph3_price.png")
print("Graph3 saved!")
top10 = df['Product'].value_counts().head(10).index.tolist()
basket_top10 = basket[top10]
corr = basket_top10.corr()
corr.to_csv("product_association_matrix.csv")
print("Graph4: Association matrix saved as CSV!")
plt.figure(figsize=(10,6))
(basket_top10.sum().sort_values(ascending=False)).plot(kind='bar', color='purple')
plt.title("Graph 4: Product Association - Top 10 Co-occurring Products")
plt.xlabel("Product")
plt.ylabel("Number of Transactions Together")
plt.xticks(rotation=45)
plt.tight_layout()
plt.savefig("graph4_association.png")
print("Graph4 saved!")
df['Month'] = df['Date'].dt.to_period('M').astype(str)
monthly_trend = df.groupby('Month').size()
plt.figure(figsize=(10,6))
plt.plot(monthly_trend.index, monthly_trend.values, marker='o', color='red')
plt.title("Graph 5: Monthly Purchase Trend (Transactions Over Time)")
plt.xlabel("Month")
plt.ylabel("Number of Purchases")
plt.xticks(rotation=60)
plt.tight_layout()
plt.savefig("graph5_monthly_trend.png")
print("Graph5 saved!")

print("All 5 Visualizations Created Successfully!")